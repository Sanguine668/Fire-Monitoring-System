    section.right_margin = Cm(2.5)
    add_page_number_footer(doc)

    title = doc.add_paragraph()
    run = title.add_run("工作任务分解库（工作包明细表）")
    set_run_font(run, cjk=HEAD_CJK, size=Pt(18), bold=True)

    sub = doc.add_paragraph()
